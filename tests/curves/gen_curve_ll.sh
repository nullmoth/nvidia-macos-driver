#!/bin/bash
# Regenerates translator/translator/src/native/curve_intersect.ll from curve_intersect.metal (needs the Metal toolchain).
# The IR keeps only the intersector and its helper: renamed into the nvmtl namespace, internal, with attribute groups
# and loop metadata removed so it can be appended to any module.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
out="$here/../../translator/translator/src/native/curve_intersect.ll"
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
xcrun metal -target air64-apple-macos15.7 -O2 -S -emit-llvm "$here/curve_intersect.metal" -o "$tmp/c.ll"
python3 - "$tmp/c.ll" "$out" <<'PY'
import re, sys
src = open(sys.argv[1]).read().splitlines()
body, keep, decls = [], False, set()
for l in src:
    if l.startswith('define '): keep = True
    if keep:
        l = re.sub(r', !llvm\.loop !\d+', '', l)
        l = re.sub(r' #\d+', '', l)
        l = l.replace(' local_unnamed_addr', '').replace(' unnamed_addr', '')
        body.append(l)
        decls.update(re.findall(r'@(air\.[A-Za-z0-9_.]+)', l))
    if l == '}': keep = False; body.append('')
text = '\n'.join(body)
names = {}
for k, m in enumerate(re.finditer(r'define [^@]*@([A-Za-z0-9_.]+)\(', text)):
    names[m.group(1)] = 'nvmtl.curve_intersect' if 'nvmtl_curve_intersect' in m.group(1) else 'nvmtl.curve_helper%d' % k
for old, new in names.items(): text = text.replace('@' + old + '(', '@' + new + '(')
text = text.replace('define <4 x float> @nvmtl.curve_intersect(', 'define internal <4 x float> @nvmtl.curve_intersect(')
dl = [l for l in src if l.startswith('declare ') and any('@' + d + '(' in l for d in decls)]
dl = [re.sub(r' #\d+', '', l).replace(' local_unnamed_addr', '') for l in dl]
open(sys.argv[2], 'w').write('; generated by tests/curves/gen_curve_ll.sh from tests/curves/curve_intersect.metal - do not edit\n' + text.rstrip() + '\n' + '\n'.join(dl) + '\n')
PY
echo "wrote $out"
