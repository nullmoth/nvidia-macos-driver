#!/usr/bin/env python3
"""Writes plugin/nvmtl4_enum_names.h: name tables for the Metal enums the pipelines script prints by name.
Run with the macOS 27 SDK selected; the output is committed so the plugin build does not need this script."""
import re, subprocess, sys, os
H = subprocess.check_output(['xcrun', '--show-sdk-path']).decode().strip() + '/System/Library/Frameworks/Metal.framework/Headers/'
ENUMS = [('MTLPixelFormat.h', 'MTLPixelFormat'), ('MTLVertexDescriptor.h', 'MTLVertexFormat'),
         ('MTLRenderPipeline.h', 'MTLBlendFactor'), ('MTLRenderPipeline.h', 'MTLBlendOperation'),
         ('MTLVertexDescriptor.h', 'MTLVertexStepFunction'), ('MTLRenderPipeline.h', 'MTLPrimitiveTopologyClass'),
         ('MTLRenderPipeline.h', 'MTLTessellationPartitionMode')]
out = ['/* Generated by tools/gen_mtl4_enum_names.py - do not edit. */', '#ifndef NVMTL4_ENUM_NAMES_H', '#define NVMTL4_ENUM_NAMES_H', '']
for fn, t in ENUMS:
    s = open(H + fn).read()
    m = re.search(r'typedef NS_(?:ENUM|OPTIONS)\([^,]+,\s*' + t + r'\)\s*\{(.*?)\}', s, re.S)
    if not m:
        sys.exit('enum %s not found in %s' % (t, fn))
    body = re.sub(r'/\*.*?\*/|//[^\n]*', '', m.group(1), flags=re.S)
    items = re.findall(r'\b' + t + r'(\w+)\s*(?:API_\w+\([^)]*\)(?:\s*API_\w+\([^)]*\))*\s*)?(?:=\s*([^,\n]+))?\s*[,\n]', body + '\n')
    out.append('static const struct { long v; const char *n; } nv4_names_%s[] = {' % t)
    nxt = 0
    for name, val in items:
        if val.strip():
            try: nxt = int(eval(val.strip().replace('MTL' + t[3:], ''), {}))
            except Exception: pass
        out.append('    { %d, "%s" },' % (nxt, name)); nxt += 1
    out.append('    { 0, 0 } };')
    out.append('')
out.append('#endif')
open(os.path.join(os.path.dirname(__file__), '..', 'plugin', 'nvmtl4_enum_names.h'), 'w').write('\n'.join(out) + '\n')
