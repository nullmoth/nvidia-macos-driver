#!/usr/bin/env python3
"""make_app_shader_patch.py <original.spv> <edited.spv> <name> <out.inc>

Writes the word-level edit that turns one translated SPIR-V module into its edited form, as the C include an application
profile carries (plugin/nvmtl_app_profile.h). Only the edit is written: hunks of { keep, drop, add, <add words> } over
the module's 32-bit words, plus the FNV-1a hash of the module before and after. The plugin applies the edit only to a
module that hashes to the first value, and keeps the result only if it hashes to the second.

The script applies its own patch to the original and stops unless the result is the edited module, byte for byte.
With no original at hand (`-` as original.spv), it writes an empty edit: the profile then changes no shader."""
import difflib, struct, sys

def fnv(b):
    h = 2166136261
    for x in b: h = ((h ^ x) * 16777619) & 0xffffffff
    return h

def words(b):
    if len(b) % 4 or len(b) < 20 or struct.unpack_from('<I', b)[0] != 0x07230203:
        sys.exit('STOP: not a little-endian SPIR-V module')
    return list(struct.unpack('<%dI' % (len(b) // 4), b))

def apply(orig, patch):
    out, pos, i = [], 0, 0
    while i < len(patch):
        keep, drop, add = patch[i:i + 3]
        out += orig[pos:pos + keep]; pos += keep + drop
        out += patch[i + 3:i + 3 + add]; i += 3 + add
    return out + orig[pos:]

def main():
    if len(sys.argv) != 5: sys.exit(__doc__)
    src, dst, name, out = sys.argv[1:]
    up = name.upper()
    if src == '-':
        body = (f'/* {name}: no shader edit in this build. */\n'
                f'#define NVMTL_{up}_SHADER_FROM 0u\n#define NVMTL_{up}_SHADER_TO 0u\n'
                f'static const uint32_t nvmtl_{name}_shader_patch[1] = {{ 0 }};\n')
        open(out, 'w').write(body); print('empty edit written'); return
    a_b, b_b = open(src, 'rb').read(), open(dst, 'rb').read()
    a, b = words(a_b), words(b_b)
    patch, pos = [], 0
    sm = difflib.SequenceMatcher(None, a, b, autojunk=False)
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == 'equal': continue
        patch += [i1 - pos, i2 - i1, j2 - j1] + b[j1:j2]
        pos = i2
    if apply(a, patch) != b: sys.exit('STOP: the patch does not reproduce the edited module')
    lines = ['    ' + ', '.join('0x%08x' % w for w in patch[k:k + 8]) + ',' for k in range(0, len(patch), 8)]
    added = sum(j2 - j1 for t, i1, i2, j1, j2 in sm.get_opcodes() if t != 'equal')
    body = (f'/* generated by tools/make_app_shader_patch.py: the {name} shader edit, {len(patch)} words '
            f'({added} added to a {len(a)}-word module). Only the edit is here, never the original module. */\n'
            f'#define NVMTL_{up}_SHADER_FROM 0x{fnv(a_b):08x}u\n#define NVMTL_{up}_SHADER_TO 0x{fnv(b_b):08x}u\n'
            f'static const uint32_t nvmtl_{name}_shader_patch[{len(patch)}] = {{\n' + '\n'.join(lines) + '\n};\n')
    open(out, 'w').write(body)
    print(f'{name}: from {fnv(a_b):08x} to {fnv(b_b):08x}, patch {len(patch)} words, module {len(a)} -> {len(b)} words')

if __name__ == '__main__':
    main()
