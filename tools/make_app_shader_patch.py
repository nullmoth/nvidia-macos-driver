#!/usr/bin/env python3
"""make_app_shader_patch.py <original.spv> <edited.spv> <name> <out.inc>

Writes the edit that turns one translated SPIR-V module into a known-good edited module, as the C include an application
profile carries (plugin/nvmtl_app_profile.h, nvmtl_spv_apply_edit). The edited module must be the original with
instructions added in one place and its IDs renumbered (what assembling an edited disassembly produces). The edit then
holds only the edited header, the added instructions, the ID map and a bitmap of which original words are IDs - none
of the original module's instructions.

The script applies its own edit to the original (the same algorithm as the plugin) and stops unless the result is the
edited module, byte for byte. With `-` as original.spv it writes an empty edit: the profile then changes no shader."""
import difflib, struct, sys

MAGIC = 0x3245564e

def fnv(b):
    h = 2166136261
    for x in b: h = ((h ^ x) * 16777619) & 0xffffffff
    return h

def words(b):
    if len(b) % 4 or len(b) < 20 or struct.unpack_from('<I', b)[0] != 0x07230203:
        sys.exit('STOP: not a little-endian SPIR-V module')
    return list(struct.unpack('<%dI' % (len(b) // 4), b))

def insts(w):
    out, i = [], 5
    while i < len(w):
        wc = w[i] >> 16
        if wc == 0 or i + wc > len(w): sys.exit('STOP: malformed instruction stream')
        out.append((i, w[i:i + wc])); i += wc
    return out

def apply(a, e):
    at, nadd = e[4], e[5]; add = e[6:6 + nadd]; nmap = e[6 + nadd]; m = e[7 + nadd:7 + nadd + nmap]
    bits = e[8 + nadd + nmap:]
    out = [a[0], e[1], e[2], e[3], a[4]]
    for w in range(5, len(a)):
        if w == at: out += add
        v = a[w]
        if (bits[w >> 5] >> (w & 31)) & 1:
            if v >= len(m) or not m[v]: return None
            v = m[v]
        out.append(v)
    if at == len(a): out += add
    return out

def main():
    if len(sys.argv) != 5: sys.exit(__doc__)
    src, dst, name, out = sys.argv[1:]
    up = name.upper()
    if src == '-':
        open(out, 'w').write(f'/* {name}: no shader edit in this build. */\n#define NVMTL_{up}_SHADER_FROM 0u\n'
                             f'#define NVMTL_{up}_SHADER_TO 0u\nstatic const uint32_t nvmtl_{name}_shader_patch[1] = {{ 0 }};\n')
        print('empty edit written'); return
    a_b, b_b = open(src, 'rb').read(), open(dst, 'rb').read()
    a, b = words(a_b), words(b_b)
    ia, ib = insts(a), insts(b)
    sm = difflib.SequenceMatcher(None, [x[1][0] for x in ia], [x[1][0] for x in ib], autojunk=False)
    ops = [op for op in sm.get_opcodes() if op[0] != 'equal']
    if len(ops) != 1 or ops[0][0] != 'insert':
        sys.exit('STOP: the edited module is not the original plus one block of added instructions: %r' % ops[:4])
    _, i1, _, j1, j2 = ops[0]
    at = ia[i1][0] if i1 < len(ia) else len(a)
    add = [x for k in range(j1, j2) for x in ib[k][1]]
    kept = ib[:j1] + ib[j2:]
    m, bits = {}, [0] * ((len(a) + 31) // 32)
    for (pa, wa), (_, wb) in zip(ia, kept):
        if len(wa) != len(wb): sys.exit('STOP: an instruction changed length, not only its IDs')
        for k, (x, y) in enumerate(zip(wa, wb)):
            if x == y: continue
            if k == 0: sys.exit('STOP: an opcode changed')
            if m.setdefault(x, y) != y: sys.exit('STOP: ID %d maps to two new IDs' % x)
            bits[(pa + k) >> 5] |= 1 << ((pa + k) & 31)
    mp = [0] * (max(m) + 1)
    for k, v in m.items(): mp[k] = v
    e = [MAGIC, b[1], b[2], b[3], at, len(add)] + add + [len(mp)] + mp + [len(bits)] + bits
    if apply(a, e) != b: sys.exit('STOP: the edit does not reproduce the edited module')
    lines = ['    ' + ', '.join('0x%08x' % w for w in e[k:k + 8]) + ',' for k in range(0, len(e), 8)]
    body = (f'/* generated by tools/make_app_shader_patch.py: the {name} shader edit ({len(e)} words: the edited header, '
            f'{len(add)} words of added instructions, a {len(mp)}-entry ID map and a {len(bits)}-word ID bitmap). It '
            f'reproduces the known-good module exactly and carries none of the original module\'s instructions. */\n'
            f'#define NVMTL_{up}_SHADER_FROM 0x{fnv(a_b):08x}u\n#define NVMTL_{up}_SHADER_TO 0x{fnv(b_b):08x}u\n'
            f'static const uint32_t nvmtl_{name}_shader_patch[{len(e)}] = {{\n' + '\n'.join(lines) + '\n};\n')
    open(out, 'w').write(body)
    print(f'{name}: from {fnv(a_b):08x} to {fnv(b_b):08x} ({len(b_b)} B), edit {len(e)} words, '
          f'{sum(bin(x).count("1") for x in bits)} IDs renumbered, {len(add)} words added')

if __name__ == '__main__':
    main()
