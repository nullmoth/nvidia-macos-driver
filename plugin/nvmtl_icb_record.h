/* the scratch index buffer holds cap 32-bit indices per slot; its size is bounded, and the cap shrinks to fit (never below 1) */
#define NVMTL_ICB_INDEX_BUDGET (256ull << 20)
static inline uint32_t nvmtl_icb_index_cap(uint32_t slots, uint32_t wanted)
{
    if (!slots || !wanted) return 0;
    const uint64_t fit = NVMTL_ICB_INDEX_BUDGET / 4u / slots;
    return fit ? (uint32_t)(wanted < fit ? wanted : fit) : 0u;
}
/* reference of the index copy for one slot: fills dst[0..count) (the cap block), returns the number of indices copied */
static inline uint32_t nvmtl_icb_index_copy_ref(const nvmtl_icb_record *r, uint32_t slot, uint32_t cap, uint32_t loc, uint32_t len, uint32_t *dst)
{
    if (slot < loc || slot - loc >= len) return 0;
    if ((r->flags & 7u) != (NVMTL_ICB_REC_ARMED | NVMTL_ICB_REC_INDEXED)) return 0;
    if (r->count > cap) return 0;
    for (uint32_t k = 0; k < r->count; k++)
        dst[k] = (r->flags & NVMTL_ICB_REC_INDEX32) ? ((const uint32_t *)(uintptr_t)r->index)[k] : ((const uint16_t *)(uintptr_t)r->index)[k];
    return r->count;
}

