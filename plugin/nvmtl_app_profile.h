/* The profile for this process, or NULL. Both must hold: the executable name matches exactly (a helper, a renamed copy,
   or another case is a different program) and the main bundle's identifier starts with the profile's prefix (another
   program that happens to share the name is not the game). `off` is the value of NVMTL_APP_PROFILE (NULL when unset);
   "0" turns every profile off. */
static inline const nvmtl_app_profile *nvmtl_app_profile_for(const char *exe, const char *bundle_id, const char *off)
{
    if (!exe || !*exe || !bundle_id || (off && !strcmp(off, "0"))) return NULL;
    for (size_t i = 0; i < sizeof nvmtl_app_profiles / sizeof nvmtl_app_profiles[0]; i++) {
        const nvmtl_app_profile *p = &nvmtl_app_profiles[i];
        if (!strcmp(p->exe, exe) && !strncmp(bundle_id, p->bundle_prefix, strlen(p->bundle_prefix))) return p;
    }
    return NULL;
}

/* "major[.minor[.patch]]" into v; 1 when the major is a plausible macOS version (14..99). */
static inline int nvmtl_os_version_parse(const char *s, long v[3])
{
    v[0] = v[1] = v[2] = 0;
    if (!s || !*s) return 0;
    char *end; long x = strtol(s, &end, 10);
    if (end == s || x < 14 || x > 99) return 0;
    v[0] = x;
    for (int i = 1; i < 3 && *end == '.'; i++) {
        const char *b = end + 1; x = strtol(b, &end, 10);
        if (end == b || x < 0 || x > 999) return 0;
        v[i] = x;
    }
    return *end == 0;
}
static inline int nvmtl_os_version_cmp(const long a[3], const long b[3])
{
    for (int i = 0; i < 3; i++) if (a[i] != b[i]) return a[i] < b[i] ? -1 : 1;
    return 0;
}
/* The operating system version this process is told, if any. Returns 1 and fills out, or 0 for the real answer.
   env_ver is NVMTL_OS_VERSION as this process may use it (its kept environment or nvrm610.conf; NULL when unset):
   "0" turns the answer off even for a profile, a valid version is used as given (an explicit request, any process).
   Otherwise the matched profile's os_version applies, and only when the real system is older: the answer never lowers
   the version and never reaches a process without a profile. */
static inline int nvmtl_os_version_answer(const char *exe, const char *bundle_id, const char *profile_off,
                                          const char *env_ver, const long real[3], long out[3])
{
    if (env_ver && !strcmp(env_ver, "0")) return 0;
    if (env_ver && nvmtl_os_version_parse(env_ver, out)) return 1;
    const nvmtl_app_profile *p = nvmtl_app_profile_for(exe, bundle_id, profile_off);
    if (!p || !p->os_version || !nvmtl_os_version_parse(p->os_version, out)) return 0;
    return nvmtl_os_version_cmp(real, out) < 0;
}
/* One line of nvrm610.conf: when it sets `key`, copies the value (surrounding blanks and the line end dropped) and
   returns 1. Comments, blank lines and other keys return 0. The same rules nvmtl_conf_read_file applies; a reader that
   wants the file's answer keeps the LAST line that returns 1 (the user's block sits at the end). */
static inline int nvmtl_conf_line_value(const char *line, const char *key, char *out, size_t cap)
{
    const char *p = line; size_t kl = strlen(key);
    while (*p == ' ' || *p == '\t') p++;
    if (*p == '#' || strncmp(p, key, kl)) return 0;
    p += kl;
    while (*p == ' ' || *p == '\t') p++;
    if (*p != '=') return 0;
    p++;
    while (*p == ' ' || *p == '\t') p++;
    size_t n = strlen(p);
    while (n && (p[n - 1] == '\n' || p[n - 1] == '\r' || p[n - 1] == ' ' || p[n - 1] == '\t')) n--;
    if (n + 1 > cap) return 0;
    memcpy(out, p, n); out[n] = 0;
    return 1;
}

/* Applies a profile to this process's environment. A key for which user_set(key, ctx) answers 1 keeps its value. Every
   key set is appended to rec as "KEY=VALUE" separated by ';' (the record nvrm610.conf keeps in NVMTL_CONF_SET, so a
   child process forgets exactly these). Returns how many keys were set; *kept counts the keys left to the user. */
static inline unsigned nvmtl_app_knobs_apply(const nvmtl_app_knob *knobs, unsigned nknobs, int (*user_set)(const char *key, void *ctx),
                                             void *ctx, char *rec, size_t recsz, unsigned *kept)
{
    unsigned set = 0, k = 0;
    size_t n = rec ? strlen(rec) : 0;
    for (unsigned i = 0; i < nknobs; i++) {
        const nvmtl_app_knob *kv = &knobs[i];
        if (user_set && user_set(kv->key, ctx)) { k++; continue; }
        if (setenv(kv->key, kv->value, 1)) continue;
        set++;
        if (rec && recsz > n + 1) {
            size_t want = strlen(kv->key) + strlen(kv->value) + 2;
            if (n + want < recsz) { if (n) rec[n++] = ';'; n += (size_t)snprintf(rec + n, recsz - n, "%s=%s", kv->key, kv->value); }
        }
    }
    if (kept) *kept = k;
    return set;
}

static inline unsigned nvmtl_app_profile_apply(const nvmtl_app_profile *p, int (*user_set)(const char *key, void *ctx),
                                               void *ctx, char *rec, size_t recsz, unsigned *kept)
{
    if (!p) { if (kept) *kept = 0; return 0; }
    return nvmtl_app_knobs_apply(p->knobs, p->nknobs, user_set, ctx, rec, recsz, kept);
}

/* The profile's opt-in settings, applied only when `optin` (the value of NVMTL_HWRT) is "1". Same rules as the profile
   itself: a key the user set keeps the user's value. */
static inline unsigned nvmtl_app_profile_apply_optin(const nvmtl_app_profile *p, const char *optin,
                                                     int (*user_set)(const char *key, void *ctx), void *ctx, char *rec,
                                                     size_t recsz, unsigned *kept)
{
    if (!p || !p->optin_knobs || !optin || strcmp(optin, "1")) { if (kept) *kept = 0; return 0; }
    return nvmtl_app_knobs_apply(p->optin_knobs, p->noptin, user_set, ctx, rec, recsz, kept);
}

/* The matched application's own shader-cache root: <caches>/nvmtl/apps/<bundle id>. Its translated shaders and AIR
   text then never share a folder with another process's, whatever modes that process runs in. Returns 0 (no root) when
   the identifier is empty, holds anything but letters, digits, '.', '-' or '_', starts with '.', or does not fit. */
static inline int nvmtl_app_cache_root(char *out, size_t cap, const char *caches, const char *bundle_id)
{
    if (!out || !cap || !caches || !*caches || !bundle_id || !*bundle_id || bundle_id[0] == '.') return 0;
    for (const char *c = bundle_id; *c; c++)
        if (!((*c >= 'a' && *c <= 'z') || (*c >= 'A' && *c <= 'Z') || (*c >= '0' && *c <= '9') || *c == '.' || *c == '-' || *c == '_'))
            return 0;
    const int k = snprintf(out, cap, "%s/nvmtl/apps/%s", caches, bundle_id);
    return k > 0 && (size_t)k < cap;
}

/* The hash the plugin has always used to recognise a translated module: FNV-1a over its bytes. */
static inline uint32_t nvmtl_spv_fnv1a(const void *bytes, size_t len)
{
    const uint8_t *b = (const uint8_t *)bytes; uint32_t h = 2166136261u;
    for (size_t i = 0; i < len; i++) { h ^= b[i]; h *= 16777619u; }
    return h;
}

/* The edit reproduces one known-good module exactly from the translator's output, without carrying the application's
   code. The two differ only in ID numbering, the header, and a few added instructions, so the edit holds just those:
     [0] 0x3245564e ("NVE2")   [1] version  [2] generator  [3] id bound   (the edited module's header words)
     [4] at: the original word offset where the added instructions go   [5] nadd, then nadd words (the added instructions)
     then nmap, then nmap words: map[old id] = new id (0 = no mapping)
     then nbits, then nbits words: bit w set = original word w is an ID operand and is renumbered through map
   Returns a malloc'd module (*outn words) when the input hashes to `from` and the result hashes to `to`; otherwise NULL
   and the caller keeps the original. A malformed edit, a short module, an unmapped ID or a wrong result all return NULL. */
#define NVMTL_SPV_EDIT_MAGIC 0x3245564eu
static inline uint32_t *nvmtl_spv_apply_edit(const uint32_t *in, size_t n, const uint32_t *e, size_t ne,
                                             uint32_t from, uint32_t to, size_t *outn)
{
    if (!in || n < 5 || !e || ne < 7 || e[0] != NVMTL_SPV_EDIT_MAGIC || in[0] != 0x07230203u) return NULL;
    const size_t at = e[4], nadd = e[5];
    if (at < 5 || at > n || 6 + nadd + 1 > ne) return NULL;
    const uint32_t *add = e + 6;
    const size_t nmap = e[6 + nadd];
    if (6 + nadd + 1 + nmap + 1 > ne) return NULL;
    const uint32_t *map = e + 6 + nadd + 1;
    const size_t nbits = e[6 + nadd + 1 + nmap];
    const uint32_t *bits = e + 6 + nadd + 1 + nmap + 1;
    if (6 + nadd + 1 + nmap + 1 + nbits != ne || nbits * 32 < n) return NULL;
    if (nvmtl_spv_fnv1a(in, n * 4) != from) return NULL;
    uint32_t *out = (uint32_t *)malloc((n + nadd) * 4);
    if (!out) return NULL;
    size_t o = 0;
    out[o++] = in[0]; out[o++] = e[1]; out[o++] = e[2]; out[o++] = e[3]; out[o++] = in[4];
    for (size_t w = 5; w < n; w++) {
        if (w == at) { memcpy(out + o, add, nadd * 4); o += nadd; }
        uint32_t v = in[w];
        if ((bits[w >> 5] >> (w & 31)) & 1u) {
            if (v >= nmap || !map[v]) { free(out); return NULL; }
            v = map[v];
        }
        out[o++] = v;
    }
    if (at == n) { memcpy(out + o, add, nadd * 4); o += nadd; }
    if (nvmtl_spv_fnv1a(out, o * 4) != to) { free(out); return NULL; }
    *outn = o;
    return out;
}
/* The profile's kernel edit for one module about to become a compute pipeline: the edited module (malloc'd, *outn words)
   when this module is exactly the one the edit was made from, else NULL and the module is used as it is. */
static inline uint32_t *nvmtl_app_profile_edit_module(const nvmtl_app_profile *p, const void *bytes, size_t len, size_t *outn)
{
    if (!p || !p->shader_from || !bytes || (len & 3u)) return NULL;
    return nvmtl_spv_apply_edit((const uint32_t *)bytes, len / 4, p->patch, p->npatch, p->shader_from, p->shader_to, outn);
}
