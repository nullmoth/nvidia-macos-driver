#!/usr/bin/env python3
# gen_dispatch.py <gliDispatch.h of the release> <symbol list of Mesa's libglapi.a> <out.c> [report.txt]
#
# Writes the C file that fills Apple's per-context function table (the public structure GLIFunctionDispatch) for one
# release. Each slot gets one of three things:
#   - a thunk into Mesa: Mesa's API layer has an entry stub per GL function (_dispatch_stub_<Name>) that jumps
#     through the dispatch table of the thread's current Mesa context, so the thunk first makes the context that
#     the caller passed current for the thread (nm_gl_enter) and then calls the stub with the remaining arguments;
#   - one of our implementations of an Apple extension (nm_apple_ext.c), which take the engine context themselves;
#   - a refusal: the entry records GL_INVALID_OPERATION on the context and returns zero. A slot is never left empty,
#     because callers jump through the table without testing it.
# The table is filled by member name, so the layout is whatever the release's header says; nothing here depends on
# slot numbers.
import re, sys
hdr, symfile, out = sys.argv[1], sys.argv[2], sys.argv[3]
report = sys.argv[4] if len(sys.argv) > 4 else None
stubs = {l.split()[-1][len("__dispatch_stub_"):] for l in open(symfile) if "__dispatch_stub_" in l}
APPLE = {"flush_render_APPLE", "finish_render_APPLE", "swap_APPLE", "gen_fences_APPLE", "delete_fences_APPLE",
         "set_fence_APPLE", "is_fence_APPLE", "test_fence_APPLE", "finish_fence_APPLE", "test_object_APPLE",
         "finish_object_APPLE", "object_purgeable_APPLE", "object_unpurgeable_APPLE", "get_object_parameteriv_APPLE",
         "texture_range_APPLE", "get_tex_parameter_pointerv_APPLE", "label_object_with_responsible_process_APPLE"}
SUFFIX = ("ARB", "EXT", "APPLE", "ATI", "NV", "SGIS", "SGI", "IBM", "OES")
def camel(n): return "".join(p[:1].upper() + p[1:] for p in n.split("_"))
def candidates(n):
    c = camel(n); out = [c]
    m = re.fullmatch(r"(.+?)(" + "|".join(SUFFIX) + ")", c)
    if m: out.append(m.group(1))                       # header carries a suffix Mesa dropped
    else: out += [c + s for s in ("ARB", "EXT")]       # header is the core spelling of a function Mesa names by extension
    # indexed state: the header spells them _indexed_EXT, Mesa by the core "i" names
    m = re.fullmatch(r"(Enable|Disable|IsEnabled)IndexedEXT", c)
    if m: out.append(m.group(1) + "i")
    if c == "ColorMaskIndexedEXT": out.append("ColorMaski")
    m = re.fullmatch(r"Get(Integer|Boolean)IndexedvEXT", c)
    if m: out.append("Get" + m.group(1) + "i_v")
    return out
# Entries whose Mesa name cannot be derived from the header spelling.
ALIAS = {"get_integer64v_sync": "GetInteger64v", "use_program_object_ARB": "UseProgram",
         "point_size_pointer": "PointSizePointerOES", "framebuffer_texture_face_EXT": "FramebufferTextureFaceARB"}
# Last resort: the same letters and digits in a different case or with underscores placed differently
# (blend_func_i is BlendFunci, vertex_attribl1d is VertexAttribL1d, get_internal_formativ is GetInternalformativ).
NORM = {}
for st in stubs: NORM.setdefault(st.replace("_", "").lower(), st)
def resolve(n):
    if n in ALIAS: return ALIAS[n] if ALIAS[n] in stubs else None
    for c in candidates(n):
        if c in stubs: return c
    for c in candidates(n):
        k = c.replace("_", "").lower()
        if k in NORM: return NORM[k]
    return None
src = open(hdr, errors="replace").read()
body = src[src.index("typedef struct __GLIFunctionDispatchRec"):]
entries = re.findall(r"^\s*([A-Za-z_][\w \*]*?)\s*\(\*\s*(\w+)\s*\)\s*\(\s*GLIContext\s+ctx\s*(?:,\s*(.*?))?\)\s*;", body, re.M)
def argnames(a):
    if not a.strip(): return []
    names = []
    for p in [x.strip() for x in a.split(",")]:
        m = re.search(r"(\w+)\s*(\[\d*\])?$", p)
        names.append(m.group(1))
    return names
lines = ['/* Generated by gen_dispatch.py from the release\'s gliDispatch.h and the symbol list of Mesa\'s API layer. Do not edit. */',
         '#include <OpenGL/gliDispatch.h>', '#include "nm_glue.h"', '']
n_mesa = n_apple = n_refused = 0; refused = []; fills = []
for ret, name, args in entries:
    ret = ret.strip(); an = argnames(args); sig = "GLIContext ctx" + (", " + args if args.strip() else "")
    call = ", ".join(an); isvoid = ret == "void"
    if name in APPLE:
        n_apple += 1
        lines.append(f"extern {ret} nm_apple_{name}({sig});")
        fills.append((name, f"nm_apple_{name}")); continue
    tgt = resolve(name)
    if tgt:
        n_mesa += 1
        lines.append(f"extern {ret} _dispatch_stub_{tgt}({args if args.strip() else 'void'});")
        lines.append(f"static {ret} nm_t_{name}({sig}) {{ nm_gl_enter(ctx); {'' if isvoid else 'return '}_dispatch_stub_{tgt}({call}); }}")
        fills.append((name, f"nm_t_{name}"))
    else:
        n_refused += 1; refused.append(name)
        unused = "".join(f" (void){a};" for a in an)
        lines.append(f"static {ret} nm_r_{name}({sig}) {{{unused} nm_gl_refuse(ctx, \"{name}\"); {'' if isvoid else 'return (' + ret + ')0;'} }}")
        fills.append((name, f"nm_r_{name}"))
lines += ["", f"_Static_assert(sizeof(GLIFunctionDispatch) == {len(entries)} * sizeof(void *), \"every slot of the table is covered\");",
          "const unsigned nm_dispatch_slot_count = %d;" % len(entries),
          "void nm_fill_dispatch(GLIFunctionDispatch *d)", "{"]
lines += [f"    d->{n} = {f};" for n, f in fills] + ["}", ""]
open(out, "w").write("\n".join(lines))
msg = (f"table entries {len(entries)}: into Mesa {n_mesa}, Apple extensions of ours {n_apple}, refused {n_refused}; "
       f"Mesa entry stubs known {len(stubs)}; controls: begin -> {resolve('begin')}, blend_func_i -> {resolve('blend_func_i')}, "
       f"invented entry -> {resolve('not_a_real_entry')}")
print(msg)
if report: open(report, "w").write(msg + "\nrefused:\n" + "\n".join(refused) + "\n")
