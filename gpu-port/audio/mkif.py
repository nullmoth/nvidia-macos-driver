#!/usr/bin/env python3
"""mkif.py <iface.m> <out.h>: a FreeBSD kobj interface (.m) as a header for the FreeBSD-on-xnu layer.

FreeBSD's makeobjops.awk builds method descriptors and a per-class cache; bsdcompat dispatches by method NAME instead
(device methods through nmx_device_method, the sound core's channel and mixer classes through nmx_kobj_method). Each
METHOD becomes a typedef plus an inline caller that looks the method up by "<interface>_<method>" and falls back to the
DEFAULT the interface names. CODE blocks (the defaults) and HEADER blocks are copied into the header as they are."""
import re
import sys


def blocks(text, word):
    """Bodies of `word { ... };` blocks, braces balanced."""
    out, i = [], 0
    while True:
        m = re.search(r"^\s*" + word + r"\s*\{", text[i:], re.M)
        if not m:
            return out
        start = i + m.end()
        depth, j = 1, start
        while depth:
            depth += {"{": 1, "}": -1}.get(text[j], 0)
            j += 1
        out.append(text[start:j - 1])
        i = j


def main(src, dst):
    raw = open(src).read()
    text = re.sub(r"^#.*$", "", raw, flags=re.M)            # .m comments are '#' lines
    iface = re.search(r"^\s*INTERFACE\s+(\w+)\s*;", text, re.M).group(1)
    code, header = blocks(text, "CODE"), blocks(text, "HEADER")
    for b in code + header:                                  # keep METHOD parsing away from copied C
        text = text.replace(b, "")
    guard = f"NMX_{iface.upper()}_IF_H"
    out = [f"/* generated by mkif.py from {src.split('/')[-1]}; do not edit */",
           f"#ifndef {guard}", f"#define {guard}", "#include <sys/bus.h>", '#include "nmx_kobj.h"']
    out += header
    out += ["#pragma clang diagnostic push", '#pragma clang diagnostic ignored "-Wunused-function"'] + code + \
           ["#pragma clang diagnostic pop"]
    meth = re.compile(r"(STATIC)?METHOD\s+(.+?)\s+(\w+)\s*\{(.*?)\}\s*(?:DEFAULT\s+(\w+)\s*)?;", re.S)
    for static, ret, name, body, default in meth.findall(text):
        args = [a.strip() for a in body.split(";") if a.strip()]
        names = [re.search(r"(\w+)\s*(\[\s*\])?$", a).group(1) for a in args]
        full = f"{iface}_{name}"
        out.append(f"typedef {ret} {full}_t({', '.join(args) or 'void'});")
        first, ftype = names[0], args[0]
        if "device_t" in ftype:
            look = f"nmx_device_method({first}, \"{full}\")"
        else:
            look = f"nmx_kobj_method({first}->ops, \"{full}\")"
        call = f"f({', '.join(names)})"
        fallback = f"{default}" if default else "NULL"
        ret_kw = "" if ret.strip() == "void" else "return "
        out.append(f"static __inline {ret} {full.upper()}({', '.join(args)})\n{{\n"
                   f"\t{full}_t *f = ({full}_t *){look};\n"
                   f"\tif (f == NULL) f = {fallback};\n"
                   f"\t{ret_kw}{call};\n}}")
    out.append(f"#endif /* {guard} */")
    open(dst, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
